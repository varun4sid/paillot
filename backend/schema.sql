-- Run this in the Supabase SQL Editor (or any PostgreSQL 13+).
-- Big integers (n, g, ciphertexts) are stored as base-10 TEXT because
-- 1024/2048-bit values far exceed PostgreSQL's 64-bit BIGINT.

-- 1. Users Table (Poll Creators)
CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Polls Table
CREATE TABLE IF NOT EXISTS polls (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    creator_id UUID REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    candidates JSONB NOT NULL,          -- Array of strings, max 10 candidates
    base_m INTEGER NOT NULL DEFAULT 1000,
    max_votes INTEGER NOT NULL DEFAULT 999,
    pub_n TEXT NOT NULL,                -- Base-10 string of modulus n
    pub_g TEXT NOT NULL,                -- Base-10 string of generator g
    is_active BOOLEAN DEFAULT TRUE,
    encrypted_tally TEXT,               -- Base-10 string of C_total after closing
    tally_time_ms DOUBLE PRECISION,     -- Academic benchmark: server homomorphic multiply time
    plaintext_time_ms DOUBLE PRECISION, -- Academic benchmark: simulated plaintext sum time
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Votes Table (Projected live during classroom demo)
CREATE TABLE IF NOT EXISTS votes (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    poll_id UUID REFERENCES polls(id) ON DELETE CASCADE,
    voter_uuid UUID NOT NULL,           -- Generated by client browser localStorage
    ciphertext TEXT NOT NULL,           -- Base-10 string of Paillier ciphertext c
    encryption_time_ms DOUBLE PRECISION,-- Client-side encryption time reported by voter
    expansion_ratio DOUBLE PRECISION,   -- Ciphertext bytes / Plaintext bytes
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(poll_id, voter_uuid)         -- Prevents double voting from same browser
);

CREATE INDEX IF NOT EXISTS idx_polls_creator ON polls(creator_id);

-- 4. Lock down Supabase's auto-generated public REST API.
-- With RLS enabled and no policies, the anon/public API key cannot read or write
-- these tables (e.g. password hashes). The FastAPI backend connects as the
-- `postgres` owner role, which bypasses RLS, so it is unaffected.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE polls ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes ENABLE ROW LEVEL SECURITY;
